def field(
	label: str,
	fieldname: str,
	fieldtype: str = "Data",
	**kwargs: Any,
) -> dict[str, Any]:
	value = {"fieldname": fieldname, "fieldtype": fieldtype, "label": label}
	value.update(kwargs)
	return value


def section(label: str, fieldname: str) -> dict[str, Any]:
	return field(label, fieldname, "Section Break")


def column(fieldname: str) -> dict[str, Any]:
	return field("", fieldname, "Column Break")


def link(label: str, fieldname: str, target: str, **kwargs: Any) -> dict[str, Any]:
	return field(label, fieldname, "Link", options=target, **kwargs)


def select(label: str, fieldname: str, options: str, **kwargs: Any) -> dict[str, Any]:
	return field(label, fieldname, "Select", options=options, **kwargs)


def table(label: str, fieldname: str, target: str, **kwargs: Any) -> dict[str, Any]:
	return field(label, fieldname, "Table", options=target, **kwargs)


