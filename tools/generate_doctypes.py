def scrub(value: str) -> str:
	return re.sub(r"[^a-z0-9]+", "_", value.lower()).strip("_")


def class_name(value: str) -> str:
	return "".join(part for part in re.split(r"[^A-Za-z0-9]+", value) if part)


def _normalized_fields(doctype: str, fields: list[dict[str, Any]]) -> list[dict[str, Any]]:
	normalized: list[dict[str, Any]] = []
	protected_fields = PHI_DISCLOSURE_FIELDS_BY_DOCTYPE.get(
		doctype, frozenset()
	) | OPERATIONAL_SENSITIVE_FIELDS_BY_DOCTYPE.get(doctype, frozenset())
	for source in fields:
		item = dict(source)
		fieldname = str(item.get("fieldname") or "")
		if fieldname in protected_fields or fieldname in DIRECT_IDENTITY_FIELD_NAMES:
			# Permlevel 9 has no generic reader permission. Runtime services may
			# still materialize these fields internally, while human disclosure
			# is limited to the governed audited endpoint.
			item["permlevel"] = 9
			item["mask"] = 1
			item.pop("in_list_view", None)
			item.pop("in_standard_filter", None)
			item.pop("search_index", None)
		if item.get("fieldtype") == "Data":
			if fieldname in LONG_IDENTIFIER_FIELDS:
				item.setdefault("length", 200)
			if fieldname in DIGEST_FIELDS or fieldname.endswith("_hash") or fieldname == "checksum":
				item.setdefault("length", 64)
		normalized.append(item)
	return normalized


def generate() -> None:
	_extend_foundation_schemas()
	_extend_indicator_schemas()
	_extend_improvement_schemas()
	_extend_integration_schemas()
	_extend_ai_schemas()
	_extend_analytics_schemas()
	_extend_admin_schemas()
	_extend_medical_record_review_schemas()
	_extend_surgery_governance_schemas()
	_extend_pdca_governance_schemas()
	_extend_quality_meeting_schemas()
	_extend_indicator_dimension_source_schemas()
	for doctype, definition in sorted(SCHEMAS.items()):
		module = definition["module"]
		module_dir = PACKAGE / scrub(module)
		doctype_dir = module_dir / "doctype" / scrub(doctype)
		doctype_dir.mkdir(parents=True, exist_ok=True)
		(module_dir / "doctype" / "__init__.py").touch(exist_ok=True)
		(doctype_dir / "__init__.py").touch(exist_ok=True)
		fields = _normalized_fields(doctype, definition["fields"])
		permissions_by_key: dict[tuple[str, int], dict[str, Any]] = {}
		for permission in definition.get("permissions", []):
			role = permission["role"]
			permlevel = int(permission.get("permlevel") or 0)
			merged = permissions_by_key.setdefault(
				(role, permlevel),
				{"role": role, "permlevel": permlevel},
			)
			for key, value in permission.items():
				if key in {"role", "permlevel"}:
					continue
				if isinstance(value, int):
					merged[key] = max(merged.get(key, 0), value)
				elif value not in (None, ""):
					merged[key] = value
		if doctype in GOVERNED_NATIVE_EXPORT_DOCTYPES:
			for permission in permissions_by_key.values():
				permission["export"] = 0
				permission["print"] = 0
		if definition.get("issingle"):
			for permission in permissions_by_key.values():
				permission["export"] = 0
				permission["report"] = 0
		payload: dict[str, Any] = {
			"actions": [],
			"allow_rename": 0,
			"autoname": definition.get("autoname", "hash"),
			"creation": TIMESTAMP,
			"doctype": "DocType",
			"engine": "InnoDB",
			"field_order": [item["fieldname"] for item in fields],
			"fields": fields,
			"index_web_pages_for_search": 0,
			"links": [],
			"modified": TIMESTAMP,
			"modified_by": "Administrator",
			"module": module,
			"name": doctype,
			"owner": "Administrator",
			"permissions": list(permissions_by_key.values()),
			"sort_field": "modified",
			"sort_order": "DESC",
			"states": [],
			"track_changes": 1,
		}
		for key in (
			"issingle",
			"istable",
			"is_submittable",
			"title_field",
			"search_fields",
			"allow_import",
			"description",
			"track_changes",
			"max_attachments",
		):
			if key in definition:
				payload[key] = definition[key]
		if payload.get("issingle") or payload.get("istable"):
			payload.pop("autoname", None)
		if payload.get("istable"):
			payload["permissions"] = []
			payload["track_changes"] = 0
		elif doctype in IDENTITY_BEARING_DOCTYPES:
			# Frappe Version rows persist an unstructured field diff sidecar.
			# These records use their governed provenance/receipt chains instead.
			payload["track_changes"] = 0
		json_path = doctype_dir / f"{scrub(doctype)}.json"
		json_path.write_text(
			json.dumps(payload, ensure_ascii=False, indent=1) + "\n",
			encoding="utf-8",
		)
		controller_path = doctype_dir / f"{scrub(doctype)}.py"
		if not controller_path.exists():
			controller_path.write_text(
				"from frappe.model.document import Document\n\n\n"
				f"class {class_name(doctype)}(Document):\n"
				"\tpass\n",
				encoding="utf-8",
			)
	print(f"Generated {len(SCHEMAS)} IONE QMS DocTypes.")


if __name__ == "__main__":
	generate()
